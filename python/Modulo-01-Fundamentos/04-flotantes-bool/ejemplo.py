print("--- Medidas Precisas ---")

# Esto es un Float (número con decimales).
# Recuerda: ¡Usa punto, no coma!
estatura_metros = 1.75
temperatura_corporal = 36.5

print("Estatura:")
print(estatura_metros)
print("Temperatura:")
print(temperatura_corporal)

print("--- Interruptores ---")

# Esto es un Booleano. 
# Solo puede ser True (Verdadero) o False (Falso).
# Sin comillas y con la primera letra en mayúscula.
traje_puesto = True
oxigeno_critico = False

print("¿Tiene el traje puesto?")
print(traje_puesto)

print("¿Nivel de oxígeno crítico?")
print(oxigeno_critico)
