print("--- Matemáticas Directas ---")

# Podemos hacer los cálculos y guardarlos directamente.
puntos_ganados = 100 + 50
print("Puntos totales:")
print(puntos_ganados)

print("--- Sumando Cajas ---")

# Es mucho más útil guardar los valores en cajas primero
# y luego hacer las operaciones matemáticas usando los nombres.
monedas_oro = 10
monedas_plata = 5

# El símbolo = toma lo de la derecha (10 + 5) y lo guarda a la izquierda.
total_monedas = monedas_oro + monedas_plata
print("Total de monedas en el inventario:")
print(total_monedas)

print("--- Multiplicación y División ---")

precio_espada = 10.5
cantidad_espadas = 3

# Usamos el asterisco (*) para multiplicar
costo_total = precio_espada * cantidad_espadas
print("Costo de las 3 espadas:")
print(costo_total)

# Usamos la barra oblicua (/) para dividir
mitad_costo = costo_total / 2
print("Si dividimos la cuenta entre dos:")
print(mitad_costo)
